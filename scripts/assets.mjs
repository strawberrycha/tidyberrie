import { createHash } from 'node:crypto'
import { mkdir, readdir, readFile, rename, stat, unlink, writeFile } from 'node:fs/promises'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath, URL } from 'node:url'
import { setTimeout as delay } from 'node:timers/promises'
import process from 'node:process'
import sharp from 'sharp'
import { z } from 'zod'
import { iconKeys, avatarKeys } from '../src/assets/stickers/keys.ts'

export const budget = 512 * 1024
const keys = [...iconKeys, ...avatarKeys]
const keySchema = z.enum(keys)
const filePattern = /^([a-z-]+)-(128|256)-[0-9a-f]{12}\.webp$/
const manifestPrefix = "// Generated by npm run assets.\nimport type { StickerManifest } from './keys'\n\n"
  + 'export const stickerManifest: StickerManifest = '
const dimensions = z.object({
  format: z.literal('png'),
  width: z.number().int().min(256).max(4096),
  height: z.number().int().min(256).max(4096),
  hasAlpha: z.literal(true),
  pages: z.literal(1).optional(),
}).refine(value => value.width === value.height)

async function optional(operation) {
  try {
    return await operation()
  } catch (error) {
    if (error.code === 'ENOENT') return undefined
    throw error
  }
}

async function encode(path) {
  const png = sharp(path, { limitInputPixels: 4096 ** 2, failOn: 'warning' })
  if (!dimensions.safeParse(await png.metadata()).success) {
    throw new Error('Use a square transparent PNG between 256 and 4096 pixels.')
  }
  const alpha = (await png.ensureAlpha().stats()).channels.at(-1)
  if (alpha.min === 255 || alpha.max === 0) throw new Error('Include both transparent and visible pixels.')

  for (const quality of [82, 72, 62, 52, 42]) {
    const variants = await Promise.all([128, 256].map(size =>
      png.clone().resize(size, size).webp({ quality, alphaQuality: 85, effort: 6 }).toBuffer()))
    if (variants.reduce((sum, variant) => sum + variant.length, 0) <= Math.floor(budget / keys.length)) return variants
  }
  throw new Error('Encoded pair exceeds the per-sticker cache allowance. Simplify the artwork.')
}

function report(manifest, bytes, ignored, inputMissing = false) {
  return {
    bytes, count: Object.keys(manifest).length, ignored, inputMissing,
    missingIcons: iconKeys.filter(key => !manifest[key]),
    missingAvatars: avatarKeys.filter(key => !manifest[key]),
  }
}

async function reportExisting(output, manifestFile) {
  const source = await optional(() => readFile(manifestFile, 'utf8'))
  if (source && !source.startsWith(manifestPrefix)) throw new Error('Generated manifest header differs.')
  const variant = z.string().refine(value => value.startsWith('/stickers/') && filePattern.test(value.slice(10)))
  const manifest = z.partialRecord(keySchema, z.strictObject({ small: variant, large: variant }))
    .parse(source ? JSON.parse(source.slice(manifestPrefix.length)) : {})
  const files = await Promise.all(Object.values(manifest).flatMap(({ small, large }) => [small, large])
    .map(path => stat(join(output, basename(path)))))
  return report(manifest, files.reduce((sum, file) => sum + file.size, 0), [], true)
}

export async function buildStickers({ input, output, manifestFile }) {
  const inputs = await optional(() => readdir(input, { withFileTypes: true }))
  if (!inputs) return reportExisting(output, manifestFile)
  const manifest = {}
  const files = new Map()
  const errors = []
  const ignored = []
  for (const entry of inputs.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isFile() || !entry.name.endsWith('.png')) continue
    const key = basename(entry.name, '.png')
    if (!keySchema.safeParse(key).success) { ignored.push(entry.name); continue }
    try {
      const [small, large] = (await encode(join(input, entry.name))).map((bytes, index) => {
        const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12)
        const file = key + '-' + (index ? 256 : 128) + '-' + hash + '.webp'
        files.set(file, bytes)
        return '/stickers/' + file
      })
      manifest[key] = { small, large }
    } catch (error) {
      if (['EBUSY', 'EPERM'].includes(error.code)) throw error
      errors.push(entry.name + ': ' + error.message)
    }
  }
  if (errors.length) throw new Error(errors.join('\n'))
  const bytes = [...files.values()].reduce((sum, file) => sum + file.length, 0)
  if (bytes > budget) throw new Error('Generated stickers exceed the cache budget.')

  await mkdir(output, { recursive: true })
  await mkdir(dirname(manifestFile), { recursive: true })
  for (const [name, contents] of files) await writeFile(join(output, name), contents)
  const source = manifestPrefix + JSON.stringify(manifest, null, 2) + '\n'
  const current = await optional(() => readFile(manifestFile, 'utf8'))
  if (current !== source) {
    const temporary = manifestFile + '.tmp'
    await writeFile(temporary, source)
    await rename(temporary, manifestFile)
  }

  for (const entry of await readdir(output, { withFileTypes: true })) {
    const match = filePattern.exec(entry.name)
    if (entry.isFile() && match && keySchema.safeParse(match[1]).success && !files.has(entry.name)) {
      await unlink(join(output, entry.name))
    }
  }
  return report(manifest, bytes, ignored)
}

async function main() {
  const root = fileURLToPath(new URL('..', import.meta.url))
  const paths = {
    input: join(root, 'design-source/stickers'),
    output: join(root, 'public/stickers'),
    manifestFile: join(root, 'src/assets/stickers/manifest.generated.ts'),
  }
  let report
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      report = await buildStickers(paths)
      break
    } catch (error) {
      if (attempt || !['EBUSY', 'EPERM'].includes(error.code)) throw error
      await delay(250)
    }
  }
  process.stdout.write([
    `${report.inputMissing ? 'Source folder absent; preserved' : 'Processed'} ${report.count} stickers (${report.bytes} / ${budget} precache bytes).`,
    'Missing icons: ' + (report.missingIcons.join(', ') || 'none'),
    'Missing avatars: ' + (report.missingAvatars.join(', ') || 'none'),
    'Ignored PNGs with unknown keys: ' + (report.ignored.join(', ') || 'none'),
  ].join('\n') + '\n')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => {
    process.stderr.write('npm run assets failed: ' + error.message + '\n')
    process.exitCode = 1
  })
}
